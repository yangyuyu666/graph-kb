import { test, expect } from "@playwright/test";

test("默认图谱和从属关系，设置可持久选择目录且独立于云端配置", async ({ page, request }) => {
  const kb = await (await request.post("/api/kbs", { data: { name: "默认视图验证" } })).json();
  const root = await (await request.post("/api/nodes", { data: { kbId: kb.id, title: "根节点" } })).json();
  await request.post("/api/nodes", { data: { kbId: kb.id, title: "另一根节点" } });
  await request.post("/api/nodes", { data: { kbId: kb.id, title: "子节点", parentId: root.id } });
  let writes = 0;
  page.on("request", r => { if (r.method() === "PATCH" && r.url().endsWith("/api/settings")) writes++; });
  const enter = () => page.getByRole("button", { name: /默认视图验证/ }).click();
  await page.goto("/");
  await enter();
  await expect(page.getByRole("tab", { name: "图谱", exact: true })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByLabel("关系筛选", { exact: true })).toHaveValue("CHILD_OF");
  const edges = () => page.locator("#graph-canvas").evaluate((el: any) => el._cyreg?.cy?.edges().map((e: any) => e.data("type")) ?? []);
  await expect.poll(edges).toEqual(["CHILD_OF"]);
  await page.getByLabel("关系筛选", { exact: true }).selectOption("");
  await expect.poll(edges).toEqual(expect.arrayContaining(["SIBLING_OF"]));
  await page.locator("#settings-nav").click();
  await expect(page.getByRole("combobox", { name: "默认视图", exact: true })).toHaveValue("graph");
  await page.getByRole("combobox", { name: "默认视图", exact: true }).selectOption("tree");
  await expect(page.getByRole("status")).toHaveText("默认视图已保存，下次进入知识库时生效");
  await page.reload();
  await page.locator("#settings-nav").click();
  await expect(page.getByRole("combobox", { name: "默认视图", exact: true })).toHaveValue("tree");
  await page.screenshot({ path: "docs/evidence/view-preferences.png", fullPage: true });
  await page.locator("#home-nav").click();
  await enter();
  await expect(page.getByRole("tab", { name: "目录", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.getByRole("tab", { name: "图谱", exact: true }).click();
  await expect(page.getByLabel("关系筛选", { exact: true })).toHaveValue("CHILD_OF");
  await page.getByRole("button", { name: "‹ 返回", exact: true }).click();
  await enter();
  await expect(page.getByRole("tab", { name: "目录", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.locator("#settings-nav").click();
  await page.getByRole("combobox", { name: "默认视图", exact: true }).selectOption("graph");
  await page.locator("#home-nav").click();
  await enter();
  await expect(page.getByRole("tab", { name: "图谱", exact: true })).toHaveAttribute("aria-selected", "true");
  expect(writes).toBe(0);
});
