import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";

test("整库导出、冲突拒绝和副本导入；首页提供明确入口", async ({ page, request }) => {
  const kb = await (await request.post("/api/kbs", { data: { name: "整库搬迁测试" } })).json();
  const root = await (await request.post("/api/nodes", { data: { kbId: kb.id, title: "原文档" } })).json();
  const child = await (await request.post("/api/nodes", { data: { kbId: kb.id, title: "子文档", parentId: root.id } })).json();
  await request.patch(`/api/nodes/${root.id}`, { data: { revision: 0, markdown: `[内部引用](node:${kb.id}/${child.id})` } });
  await page.goto("/");
  await page.getByLabel("管理知识库 整库搬迁测试", { exact: true }).click();
  const downloading = page.waitForEvent("download");
  await page.locator(".card").filter({ hasText: "整库搬迁测试" }).getByRole("button", { name: "导出知识库", exact: true }).click();
  const downloaded = await downloading;
  expect(downloaded.suggestedFilename()).toBe("整库搬迁测试.graphkb.json");
  const bytes = await readFile((await downloaded.path())!);
  const backup = JSON.parse(bytes.toString());
  expect(backup.format).toBe("graph-kb-database");
  expect(backup.nodes).toHaveLength(2);
  await page.getByRole("button", { name: "导入知识库", exact: true }).click();
  await page.getByLabel("整库备份文件").setInputFiles({ name: "backup.graphkb.json", mimeType: "application/json", buffer: bytes });
  await page.getByRole("button", { name: "导入", exact: true }).click();
  await expect(page.locator("dialog [role=alert]")).toContainText("ID 已存在");
  await page.getByLabel("导入方式").selectOption("copy");
  await page.getByRole("button", { name: "导入", exact: true }).click();
  await expect(page.locator("dialog")).toHaveCount(0);
  await expect(page.getByRole("button", { name: /整库搬迁测试（副本）/ })).toBeVisible();
  const copies = await (await request.get("/api/kbs")).json();
  const copy = copies.find((k: any) => k.name === "整库搬迁测试（副本）");
  const copyNodes = await (await request.get(`/api/kbs/${copy.id}/nodes`)).json();
  const copyRoot = copyNodes.find((n: any) => n.title === "原文档");
  const copiedChild = copyNodes.find((n: any) => n.title === "子文档");
  expect((await (await request.get(`/api/nodes/${copyRoot.id}`)).json()).markdown).toContain(`node:${copy.id}/${copiedChild.id}`);
  await page.screenshot({ path: "docs/evidence/database-transfer.png" });
});

test("跨库引用：目标未加载提示、导入恢复、引用选择器可选其他库", async ({ page, request, context }) => {
  const kb = await (await request.post("/api/kbs", { data: { name: "跨库来源" } })).json();
  const source = await (await request.post("/api/nodes", { data: { kbId: kb.id, title: "来源页" } })).json();
  const targetKb = randomUUID(), targetNode = randomUUID();
  await request.patch(`/api/nodes/${source.id}`, { data: { revision: 0, markdown: `[外部资料](node:${targetKb}/${targetNode})` } });
  const doc = await context.newPage();
  await doc.goto(`/?node=${source.id}`);
  await expect(doc.getByLabel("目标知识库未加载", { exact: true })).toBeVisible();
  await doc.getByLabel("目标知识库未加载", { exact: true }).click();
  await expect(doc.getByRole("status")).toContainText("目标知识库未加载");
  const data = { format: "graph-kb-database", version: 1, id: targetKb, name: "外部资料库", kb: { id: targetKb, name: "外部资料库" }, nodes: [{ id: targetNode, kbId: targetKb, title: "跨库目标页", kind: "Page", conceptKey: "", revision: 0, updatedAt: new Date().toISOString() }], edges: [], documents: [{ id: targetNode, markdown: "目标正文" }], assets: [], trash: [], cache: [] };
  await page.goto("/");
  await page.getByRole("button", { name: "导入知识库", exact: true }).click();
  await page.getByLabel("整库备份文件").setInputFiles({ name: "target.graphkb.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(data)) });
  await page.getByRole("button", { name: "导入", exact: true }).click();
  await expect(page.locator("dialog")).toHaveCount(0);
  await doc.reload();
  await expect(doc.locator(".deleted-reference")).toHaveCount(0);
  const popup = doc.waitForEvent("popup");
  await doc.locator(`a[href="node:${targetKb}/${targetNode}"]`).click();
  const target = await popup;
  await expect(target.locator(".ProseMirror")).toContainText("目标正文");
  await expect(target.locator(".document-links")).toContainText("来源页");
  await doc.getByRole("button", { name: "引用节点", exact: true }).click();
  await doc.getByLabel("目标知识库", { exact: true }).selectOption(targetKb);
  await expect(doc.getByLabel("目标节点", { exact: true })).toHaveValue(targetNode);
  await doc.getByRole("button", { name: "确定", exact: true }).click();
  await doc.getByRole("button", { name: "保存", exact: true }).click();
  await expect(doc.getByRole("status")).toContainText("已保存");
});
